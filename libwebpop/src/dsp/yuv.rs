//! Default, gamma-compensated RGB to YUV420 conversion. The row primitives
//! accept channel slices, so offsets and odd-edge replication stay explicit.

#![allow(non_upper_case_globals)]

use std::sync::OnceLock;

pub const YUV_FIX: u32 = 16;
pub const YUV_HALF: i32 = 1 << (YUV_FIX - 1);
const GAMMA_TAB_FIX: u32 = 7;
const GAMMA_TAB_SIZE: usize = 32;
const GAMMA_SCALE: i32 = 4095;

pub struct GammaTables {
    pub gamma_to_linear: [u16; 256],
    pub linear_to_gamma: [i32; GAMMA_TAB_SIZE + 1],
}

pub fn WebPInitGammaTables() -> &'static GammaTables {
    static TABLES: OnceLock<GammaTables> = OnceLock::new();
    TABLES.get_or_init(|| {
        let norm = 1.0 / 255.0;
        let scale = f64::from(1 << GAMMA_TAB_FIX) / f64::from(GAMMA_SCALE);
        GammaTables {
            gamma_to_linear: std::array::from_fn(|v| {
                ((norm * v as f64).powf(0.80) * f64::from(GAMMA_SCALE) + 0.5) as u16
            }),
            linear_to_gamma: std::array::from_fn(|v| {
                (255.0 * (scale * v as f64).powf(1.0 / 0.80) + 0.5) as i32
            }),
        }
    })
}

#[inline]
pub fn VP8ClipUV(uv: i32, rounding: i32) -> u8 {
    ((uv + rounding + (128 << (YUV_FIX + 2))) >> (YUV_FIX + 2)).clamp(0, 255) as u8
}

#[inline]
pub fn VP8RGBToY(r: i32, g: i32, b: i32, rounding: i32) -> u8 {
    ((16839 * r + 33059 * g + 6420 * b + rounding + (16 << YUV_FIX)) >> YUV_FIX) as u8
}

#[inline]
pub fn VP8RGBToU(r: i32, g: i32, b: i32, rounding: i32) -> u8 {
    VP8ClipUV(-9719 * r - 19081 * g + 28800 * b, rounding)
}

#[inline]
pub fn VP8RGBToV(r: i32, g: i32, b: i32, rounding: i32) -> u8 {
    VP8ClipUV(28800 * r - 24116 * g - 4684 * b, rounding)
}

#[inline]
pub fn GammaToLinear(v: u8) -> u32 {
    u32::from(WebPInitGammaTables().gamma_to_linear[usize::from(v)])
}

#[inline]
pub fn Interpolate(v: u32) -> i32 {
    let tab_pos = (v >> (GAMMA_TAB_FIX + 2)) as usize;
    let x = (v & 511) as i32;
    let table = &WebPInitGammaTables().linear_to_gamma;
    table[tab_pos + 1] * x + table[tab_pos] * (512 - x)
}

/// Input is a sum of linearized bytes, with `base_value << shift <= 16380`.
#[inline]
pub fn LinearToGamma(base_value: u32, shift: u32) -> u16 {
    ((Interpolate(base_value << shift) + 64) >> GAMMA_TAB_FIX) as u16
}

// Exactly the upstream reciprocal table, generated by integer constant
// evaluation instead of spelling out its 1021 entries.
const fn inverse_alpha_table() -> [u32; 1021] {
    let mut table = [0; 1021];
    let mut a = 1;
    while a < table.len() {
        table[a] = (1 << 19) / a as u32;
        a += 1;
    }
    table
}
pub const kInvAlpha: [u32; 1021] = inverse_alpha_table();

#[inline]
fn LinearToGammaWeighted(src: &[u8], a: &[u8], total_a: u32, step: usize, stride: usize) -> u16 {
    let sum = u32::from(a[0]) * GammaToLinear(src[0])
        + u32::from(a[step]) * GammaToLinear(src[step])
        + u32::from(a[stride]) * GammaToLinear(src[stride])
        + u32::from(a[stride + step]) * GammaToLinear(src[stride + step]);
    debug_assert!((1..=1020).contains(&total_a));
    // The pin uses the truncated reciprocal, not integer division by alpha.
    LinearToGamma((sum * kInvAlpha[total_a as usize]) >> 17, 0)
}

pub fn ConvertRGBToY_C(rgb: &[u8], y: &mut [u8], width: usize, step: usize) {
    for (i, dst) in y[..width].iter_mut().enumerate() {
        let p = &rgb[i * step..];
        *dst = VP8RGBToY(i32::from(p[0]), i32::from(p[1]), i32::from(p[2]), YUV_HALF);
    }
}

pub fn WebPConvertRGBA32ToUV_C(rgb: &[u16], u: &mut [u8], v: &mut [u8], width: usize) {
    for i in 0..width {
        let p = &rgb[4 * i..];
        u[i] = VP8RGBToU(
            i32::from(p[0]),
            i32::from(p[1]),
            i32::from(p[2]),
            YUV_HALF << 2,
        );
        v[i] = VP8RGBToV(
            i32::from(p[0]),
            i32::from(p[1]),
            i32::from(p[2]),
            YUV_HALF << 2,
        );
    }
}

pub fn WebPAccumulateRGB(
    r: &[u8],
    g: &[u8],
    b: &[u8],
    step: usize,
    rgb_stride: usize,
    dst: &mut [u16],
    width: usize,
) {
    for i in 0..width.div_ceil(2) {
        let j = 2 * i * step;
        for (c, src) in [r, g, b].into_iter().enumerate() {
            dst[4 * i + c] = if 2 * i + 1 < width {
                LinearToGamma(
                    GammaToLinear(src[j])
                        + GammaToLinear(src[j + step])
                        + GammaToLinear(src[j + rgb_stride])
                        + GammaToLinear(src[j + rgb_stride + step]),
                    0,
                )
            } else {
                LinearToGamma(
                    GammaToLinear(src[j]) + GammaToLinear(src[j + rgb_stride]),
                    1,
                )
            };
        }
        // dst[4*i+3] is deliberately untouched, as in the scalar C function.
    }
}

pub fn WebPAccumulateRGBA(
    r: &[u8],
    g: &[u8],
    b: &[u8],
    a: &[u8],
    rgb_stride: usize,
    dst: &mut [u16],
    width: usize,
) {
    for i in 0..width.div_ceil(2) {
        let j = 8 * i;
        let step = if 2 * i + 1 < width { 4 } else { 0 };
        let total_a = u32::from(a[j])
            + u32::from(a[j + step])
            + u32::from(a[j + rgb_stride])
            + u32::from(a[j + rgb_stride + step]);
        for (c, src) in [r, g, b].into_iter().enumerate() {
            dst[4 * i + c] = if total_a == 0 || total_a == 1020 {
                LinearToGamma(
                    GammaToLinear(src[j])
                        + GammaToLinear(src[j + step])
                        + GammaToLinear(src[j + rgb_stride])
                        + GammaToLinear(src[j + rgb_stride + step]),
                    0,
                )
            } else {
                LinearToGammaWeighted(&src[j..], &a[j..], total_a, step, rgb_stride)
            };
        }
        dst[4 * i + 3] = total_a as u16;
    }
}
